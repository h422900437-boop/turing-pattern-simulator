import matplotlib.pyplot as plt
import cProfile
import pstats
import io
import gc
import ctypes
import platform
from turing_core.interface import run_simulation

def run_benchmark_plot():
    """
    Run four sets of experiments (leopard/giraffe x explicit/implicit) and generate a 2x2 comparison plot including runtime.
    Integrates a garbage collection mechanism to prevent Out Of Memory (OOM) errors or system throttling when running large sparse matrix solvers consecutively.
    """
    print("Starting benchmark test... This may take a few minutes, please wait.\n")
    
    # Define the four combinations to test (parameters match the input format of run_simulation)
    configs = [
        ('leopard', 'explicit'),
        ('leopard', 'implicit'),
        ('giraffe', 'explicit'),
        ('giraffe', 'implicit')
    ]
    
    fig, axes = plt.subplots(2, 2, figsize=(12, 12))
    axes = axes.flatten()
    
    for i, (animal, scheme) in enumerate(configs):
        print(f"Calculating: {animal.capitalize()} - {scheme.capitalize()} Solver...")
        
        # Call the interface to execute the simulation
        v_matrix, gen_time = run_simulation(pattern=animal, method=scheme)
        
        # Plot the current subplot
        ax = axes[i]
        ax.imshow(v_matrix, cmap='Greys')
        ax.axis('off')
        # Prominently display the runtime of this method in the title
        ax.set_title(f"{animal.capitalize()} | {scheme.capitalize()}\nTime: {gen_time:.4f} seconds", fontsize=14, pad=10)
        
        # ==========================================
        # [Key Fix]: Forced memory garbage collection and release
        # ==========================================
        # 1. Force Python's garbage collector to clean up unreferenced objects (especially the huge SuperLU objects generated by scipy)
        gc.collect() 
        
        # 2. For Windows systems, force the C runtime library to return idle memory to the OS
        if platform.system() == 'Windows':
            try:
                ctypes.CDLL('msvcrt')._heapmin()
            except Exception as e:
                pass
        
    plt.tight_layout()
    plt.savefig('benchmark_results.png', dpi=300)
    print("-> Image saved as 'benchmark_results.png'\n")
    plt.show()

def run_profiling(animal='giraffe', scheme='explicit'):
    """
    Use cProfile to analyze the performance bottlenecks of a specific solver and locate the most time-consuming functions
    """
    print(f"Starting profiling for {animal.capitalize()} {scheme.capitalize()} solver...\n")
    
    # Initialize Profiler
    pr = cProfile.Profile()
    pr.enable()  # Start recording
    
    # Execute the target function
    run_simulation(pattern=animal, method=scheme)
    
    pr.disable() # Stop recording
    
    # Format and output the profiling results
    s = io.StringIO()
    # Sort in descending order by total internal time spent in the function (tottime)
    ps = pstats.Stats(pr, stream=s).sort_stats('tottime')
    
    # Only print the top 15 most time-consuming function calls
    ps.print_stats(15)
    
    print("=== Profiling Results (Top 15 Time-Consuming Functions) ===")
    print(s.getvalue())
    print("=====================================================")
    
    # Clean up memory after analysis as well
    gc.collect()

if __name__ == "__main__":
    # 1. Generate runtime comparison plot
    run_benchmark_plot()
    
    # 2. Locate the time bottleneck of the explicit algorithm
    # The explicit algorithm is mainly limited by the memory bandwidth of np.roll and scalar arithmetic operations
    run_profiling(animal='giraffe', scheme='explicit')
    
    # 3. Locate the time bottleneck of the implicit algorithm
    # The implicit algorithm is mainly limited by the LU decomposition and substitution operation (solve) of massive sparse matrices
    run_profiling(animal='giraffe', scheme='implicit')


    